fn is_known(value: &str, known: &[&str]) -> bool {
    known.contains(&value)
}

fn bool_value(value: bool) -> String {
    if value { "1" } else { "0" }.to_string()
}

fn parse_bool(value: Option<String>, default: bool) -> bool {
    match value.as_deref() {
        Some("1" | "true") => true,
        Some("0" | "false") => false,
        _ => default,
    }
}

/// Domains and IPs from the custom bypass list, split by the routing field
/// they belong to.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct BypassEntries {
    pub domains: Vec<String>,
    pub ips: Vec<String>,
}

/// Parses the multi-line bypass list into Xray `domain` and `ip` entries.
///
/// Blank lines and lines starting with `#` are ignored, and malformed lines
/// are skipped; [`validate_bypass_list`] reports them before the settings are
/// saved, so a stored list contains only valid entries.
pub fn bypass_entries(value: &str) -> BypassEntries {
    let mut entries = BypassEntries::default();
    for line in value.lines() {
        match classify_bypass_entry(line.trim()) {
            Some(BypassEntry::Domain(domain)) => entries.domains.push(domain),
            Some(BypassEntry::Ip(ip)) => entries.ips.push(ip),
            None => {}
        }
    }
    entries
}

/// Checks every non-comment line of the custom bypass list.
pub fn validate_bypass_list(value: &str) -> Result<(), String> {
    for (index, raw) in value.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if classify_bypass_entry(line).is_none() {
            return Err(format!(
                "Bypass list line {} is not a valid domain or IP address: {line}",
                index + 1
            ));
        }
    }
    Ok(())
}

enum BypassEntry {
    Domain(String),
    Ip(String),
}

/// The outbound a user rule sends its traffic to.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum OutboundTarget {
    Proxy,
    Direct,
    Block,
}

impl OutboundTarget {
    /// Tag of the generated outbound for this target. `proxy` is the one-node
    /// config's proxy outbound; hot-switch configs reference the balancer
    /// instead.
    pub fn tag(self) -> &'static str {
        match self {
            Self::Proxy => "proxy",
            Self::Direct => "direct",
            Self::Block => "block",
        }
    }
}

/// Which routing field a user rule belongs to.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum RuleMatcher {
    Domain(String),
    Ip(String),
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct OutboundRule {
    pub matcher: RuleMatcher,
    pub target: OutboundTarget,
}

/// Parses `<domain-or-ip> <direct|proxy|block>` lines. Blank lines, comments
/// and malformed lines are skipped; [`validate_outbound_rules`] reports the
/// malformed ones before the settings are saved.
pub fn outbound_rules(value: &str) -> Vec<OutboundRule> {
    value.lines().filter_map(parse_outbound_rule).collect()
}

pub fn validate_outbound_rules(value: &str) -> Result<(), String> {
    for (index, raw) in value.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if parse_outbound_rule(line).is_none() {
            return Err(format!(
                "Outbound rules line {} must look like `<domain-or-ip> <direct|proxy|block>`: {line}",
                index + 1
            ));
        }
    }
    Ok(())
}

fn parse_outbound_rule(line: &str) -> Option<OutboundRule> {
    let line = line.trim();
    if line.is_empty() || line.starts_with('#') {
        return None;
    }
    let mut parts = line.split_whitespace();
    let entry = parts.next()?;
    let target = match parts.next()?.to_ascii_lowercase().as_str() {
        "proxy" => OutboundTarget::Proxy,
        "direct" => OutboundTarget::Direct,
        "block" => OutboundTarget::Block,
        _ => return None,
    };
    if parts.next().is_some() {
        return None;
    }
    let matcher = match classify_bypass_entry(entry)? {
        BypassEntry::Domain(domain) => RuleMatcher::Domain(domain),
        BypassEntry::Ip(ip) => RuleMatcher::Ip(ip),
    };
    Some(OutboundRule { matcher, target })
}

/// Xray expects either the literal `tlshello` or an inclusive packet range
/// whose first packet is at least 1.
fn is_fragment_packets(value: &str) -> bool {
    value.eq_ignore_ascii_case("tlshello") || fragment_range(value, 1).is_some()
}

/// Parses `N` or `N-M` and checks that the range is ordered and its first
/// value is at least `min_start`.
fn fragment_range(value: &str, min_start: u32) -> Option<(u32, u32)> {
    let (start, end) = match value.split_once('-') {
        Some((start, end)) => (start.parse().ok()?, end.parse().ok()?),
        None => {
            let only = value.parse().ok()?;
            (only, only)
        }
    };
    (start >= min_start && end >= start).then_some((start, end))
}

/// Turns one input line into the routing entry Xray expects.
///
/// A bare domain becomes `domain:`, which also matches its subdomains; `*.`
/// is treated the same way. Xray prefixes are passed through so `geosite:`,
/// `keyword:`, `regexp:`, etc. keep their meaning.
fn classify_bypass_entry(line: &str) -> Option<BypassEntry> {
    if line.is_empty() || line.starts_with('#') {
        return None;
    }
    for prefix in ["geosite:", "domain:", "full:", "keyword:", "regexp:"] {
        if let Some(value) = line.strip_prefix(prefix) {
            return (!value.is_empty()).then(|| BypassEntry::Domain(line.to_string()));
        }
    }
    if let Some(value) = line.strip_prefix("geoip:") {
        return (!value.is_empty()).then(|| BypassEntry::Ip(line.to_string()));
    }
    if is_ip_or_cidr(line) {
        return Some(BypassEntry::Ip(line.to_string()));
    }
    let domain = line.strip_prefix("*.").unwrap_or(line);
    let domain = domain.strip_prefix('.').unwrap_or(domain);
    is_domain_name(domain).then(|| BypassEntry::Domain(format!("domain:{domain}")))
}

fn is_ip_or_cidr(value: &str) -> bool {
    if value.parse::<IpAddr>().is_ok() {
        return true;
    }
    let Some((address, prefix)) = value.split_once('/') else {
        return false;
    };
    let Ok(address) = address.parse::<IpAddr>() else {
        return false;
    };
    let Ok(prefix) = prefix.parse::<u8>() else {
        return false;
    };
    prefix <= if address.is_ipv4() { 32 } else { 128 }
}

fn is_domain_name(value: &str) -> bool {
    !value.is_empty()
        && !value.starts_with('.')
        && !value.ends_with('.')
        && value
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '.' | '_'))
}

/// Accepts the address forms Xray's DNS client supports: `1.1.1.1`,
/// `1.1.1.1:53`, `tcp://8.8.8.8`, `https://1.1.1.1/dns-query`, and hostnames
/// such as `dns.google:853`.
fn is_dns_server_address(value: &str) -> bool {
    if value.is_empty() || value.chars().any(char::is_whitespace) {
        return false;
    }
    let address = match value.split_once("://") {
        Some((scheme, rest)) => {
            let scheme = scheme.to_ascii_lowercase();
            if !matches!(
                scheme.as_str(),
                "tcp" | "udp" | "tls" | "quic" | "quic+local" | "https" | "https+local"
            ) {
                return false;
            }
            rest
        }
        None => value,
    };

    let authority = address.split(['/', '?']).next().unwrap_or("");
    if authority.is_empty() {
        return false;
    }
    if authority.parse::<IpAddr>().is_ok() {
        return true;
    }
    if let Some(rest) = authority.strip_prefix('[') {
        let Some((host, tail)) = rest.split_once(']') else {
            return false;
        };
        return host.parse::<std::net::Ipv6Addr>().is_ok()
            && (tail.is_empty() || (tail.starts_with(':') && tail[1..].parse::<u16>().is_ok()));
    }

    let (host, port) = match authority.rsplit_once(':') {
        Some((host, port)) => (host, Some(port)),
        None => (authority, None),
    };
    if port.is_some_and(|port| port.parse::<u16>().is_err()) {
        return false;
    }
    !host.is_empty() && (host.parse::<std::net::Ipv4Addr>().is_ok() || is_domain_name(host))
}

/// Returns the prefix length when `value` is a valid IPv4 CIDR.
fn ipv4_cidr(value: &str) -> Option<u8> {
    let (address, prefix) = value.trim().split_once('/')?;
    address.parse::<std::net::Ipv4Addr>().ok()?;
    let prefix = prefix.parse::<u8>().ok()?;
    (prefix <= 32).then_some(prefix)
}

