/// User-facing options that feed into every Xray config generated by the app.
///
/// The values live in SQLite (`app_settings`) so a change survives a restart,
/// and the running core is restarted with the new config when one is active.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct XraySettings {
    pub log_level: String,
    pub domain_strategy: String,
    /// Route mainland-China domains and addresses directly.
    pub bypass_cn: bool,
    /// Route private/LAN destinations directly.
    pub bypass_private: bool,
    /// Send `geosite:category-ads-all` to the blackhole outbound.
    pub block_ads: bool,
    /// Send UDP 443 to the blackhole outbound so QUIC-capable apps fall back
    /// to TCP and their traffic is routed like every other connection.
    pub block_quic: bool,
    /// Custom domains/IPs routed direct, one entry per line. Accepts plain
    /// domains, `*.domain`, CIDRs, and Xray rule prefixes.
    pub bypass_list: String,
    /// User-defined outbound rules, one `<domain-or-ip> <direct|proxy|block>`
    /// per line. They run before the automatic bypass rules, so they can
    /// override them.
    pub outbound_rules: String,
    /// Inspect proxied connections to recover the hostname from HTTP/TLS/QUIC
    /// handshakes, so domain rules also match apps that connect by IP.
    pub sniffing_enabled: bool,
    pub sniff_http: bool,
    pub sniff_tls: bool,
    pub sniff_quic: bool,
    /// Use the sniffed hostname only for routing and keep connecting to the
    /// original address.
    pub sniff_route_only: bool,
    /// Split the TLS ClientHello sent to the node into fragments (anti-DPI).
    pub fragment_enabled: bool,
    /// `tlshello` or a packet range such as `1-3`.
    pub fragment_packets: String,
    /// Bytes per fragment, e.g. `100-200`.
    pub fragment_length: String,
    /// Delay between fragments in milliseconds, e.g. `10-20`.
    pub fragment_interval: String,
    pub mux_enabled: bool,
    pub mux_concurrency: u16,
    /// Allow AAAA queries and add IPv6 addresses/routes to TUN.
    pub ipv6_enabled: bool,
    /// Resolver used for direct (China/private) domains. Empty means the
    /// system resolver.
    pub local_dns: String,
    /// Resolver used for proxied domains. Its queries are routed through the
    /// proxy, so the answer comes from the exit's region. Empty means the
    /// system resolver.
    pub remote_dns: String,
    pub fake_dns_enabled: bool,
    /// IPv4 CIDR used by FakeDNS.
    pub fake_dns_ip_pool: String,
    pub fake_dns_pool_size: u32,
    pub tun_enabled: bool,
    pub tun_name: String,
    pub tun_mtu: u32,
    /// IPv4 address prefix assigned to the TUN interface.
    pub tun_gateway: String,
    pub tun_auto_route: bool,
    /// Use split default routes so existing routes cannot win over the TUN.
    pub tun_strict_route: bool,
    /// Network stack implementation for cores that support choosing one.
    pub tun_stack: String,
    /// Expose the proxy to the local network on dedicated SOCKS/HTTP ports.
    pub lan_enabled: bool,
    /// Credentials for the LAN inbounds. Both empty means no authentication.
    pub lan_username: String,
    pub lan_password: String,
}

