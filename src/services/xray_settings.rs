use super::database::Database;

pub const DEFAULT_LOG_LEVEL: &str = "warning";
pub const LOG_LEVELS: &[&str] = &["warning", "info", "debug", "error", "none"];

pub const DEFAULT_DOMAIN_STRATEGY: &str = "IPIfNonMatch";
pub const DOMAIN_STRATEGIES: &[&str] = &["AsIs", "IPIfNonMatch", "IPOnDemand"];

pub const DEFAULT_MUX_CONCURRENCY: u16 = 8;
pub const MUX_CONCURRENCY_OPTIONS: &[u16] = &[1, 2, 4, 8, 16, 32];

pub const DEFAULT_FAKE_DNS_POOL: &str = "198.18.0.0/15";
pub const FAKE_DNS_POOL_SIZE_OPTIONS: &[u32] = &[1024, 4096, 16384, 32768, 65535];
pub const DEFAULT_FAKE_DNS_POOL_SIZE: u32 = 65535;
/// IPv6 fake addresses. Used alongside the IPv4 pool when IPv6 is enabled.
pub const DEFAULT_FAKE_DNS_IPV6_POOL: &str = "2001:2::/48";

pub const DEFAULT_TUN_NAME: &str = "cloak0";
pub const DEFAULT_TUN_MTU: u32 = 1500;
pub const TUN_MTU_OPTIONS: &[u32] = &[1280, 1380, 1420, 1500, 9000];
pub const DEFAULT_TUN_GATEWAY: &str = "10.0.0.1/16";
pub const TUN_IPV6_GATEWAY: &str = "fc00::1/64";
pub const DEFAULT_TUN_STRICT_ROUTE: bool = true;
pub const DEFAULT_TUN_STACK: &str = "mixed";
/// Network stack implementations a core may support. Xray's TUN currently has
/// one built-in stack, so the value is stored for cores that can switch.
pub const TUN_STACKS: &[&str] = &["system", "gvisor", "mixed"];

const KEY_LOG_LEVEL: &str = "xray_log_level";
const KEY_DOMAIN_STRATEGY: &str = "xray_domain_strategy";
const KEY_BYPASS_CN: &str = "xray_bypass_cn";
const KEY_BYPASS_PRIVATE: &str = "xray_bypass_private";
const KEY_BLOCK_ADS: &str = "xray_block_ads";
const KEY_MUX_ENABLED: &str = "xray_mux_enabled";
const KEY_MUX_CONCURRENCY: &str = "xray_mux_concurrency";
const KEY_IPV6_ENABLED: &str = "xray_ipv6_enabled";
const KEY_LOCAL_DNS: &str = "xray_local_dns";
const KEY_FAKE_DNS_ENABLED: &str = "xray_fake_dns_enabled";
const KEY_FAKE_DNS_POOL: &str = "xray_fake_dns_pool";
const KEY_FAKE_DNS_POOL_SIZE: &str = "xray_fake_dns_pool_size";
const KEY_TUN_ENABLED: &str = "xray_tun_enabled";
const KEY_TUN_NAME: &str = "xray_tun_name";
const KEY_TUN_MTU: &str = "xray_tun_mtu";
const KEY_TUN_GATEWAY: &str = "xray_tun_gateway";
const KEY_TUN_AUTO_ROUTE: &str = "xray_tun_auto_route";
const KEY_TUN_STRICT_ROUTE: &str = "xray_tun_strict_route";
const KEY_TUN_STACK: &str = "xray_tun_stack";

/// User-facing options that feed into every Xray config generated by the app.
///
/// The values live in SQLite (`app_settings`) so a change survives a restart,
/// and the running core is restarted with the new config when one is active.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct XraySettings {
    pub log_level: String,
    pub domain_strategy: String,
    /// Route mainland-China domains and addresses directly.
    pub bypass_cn: bool,
    /// Route private/LAN destinations directly.
    pub bypass_private: bool,
    /// Send `geosite:category-ads-all` to the blackhole outbound.
    pub block_ads: bool,
    pub mux_enabled: bool,
    pub mux_concurrency: u16,
    /// Allow AAAA queries and add IPv6 addresses/routes to TUN.
    pub ipv6_enabled: bool,
    /// Resolver used for direct (China/private) domains. Empty means the
    /// system resolver.
    pub local_dns: String,
    pub fake_dns_enabled: bool,
    /// IPv4 CIDR used by FakeDNS.
    pub fake_dns_ip_pool: String,
    pub fake_dns_pool_size: u32,
    pub tun_enabled: bool,
    pub tun_name: String,
    pub tun_mtu: u32,
    /// IPv4 address prefix assigned to the TUN interface.
    pub tun_gateway: String,
    pub tun_auto_route: bool,
    /// Use split default routes so existing routes cannot win over the TUN.
    pub tun_strict_route: bool,
    /// Network stack implementation for cores that support choosing one.
    pub tun_stack: String,
}

impl Default for XraySettings {
    fn default() -> Self {
        Self {
            log_level: DEFAULT_LOG_LEVEL.to_string(),
            domain_strategy: DEFAULT_DOMAIN_STRATEGY.to_string(),
            bypass_cn: true,
            bypass_private: true,
            block_ads: false,
            mux_enabled: false,
            mux_concurrency: DEFAULT_MUX_CONCURRENCY,
            ipv6_enabled: true,
            local_dns: String::new(),
            fake_dns_enabled: false,
            fake_dns_ip_pool: DEFAULT_FAKE_DNS_POOL.to_string(),
            fake_dns_pool_size: DEFAULT_FAKE_DNS_POOL_SIZE,
            tun_enabled: false,
            tun_name: DEFAULT_TUN_NAME.to_string(),
            tun_mtu: DEFAULT_TUN_MTU,
            tun_gateway: DEFAULT_TUN_GATEWAY.to_string(),
            tun_auto_route: true,
            tun_strict_route: DEFAULT_TUN_STRICT_ROUTE,
            tun_stack: DEFAULT_TUN_STACK.to_string(),
        }
    }
}

impl XraySettings {
    pub fn load(database: &Database) -> Self {
        Self::from_values(|key| database.get_setting(key).ok().flatten())
    }

    /// Checks the values that would make Xray refuse to start.
    pub fn validate(&self) -> Result<(), String> {
        if !LOG_LEVELS.contains(&self.log_level.as_str()) {
            return Err(format!("Unknown Xray log level: {}", self.log_level));
        }
        if !DOMAIN_STRATEGIES.contains(&self.domain_strategy.as_str()) {
            return Err(format!(
                "Unknown Xray domain strategy: {}",
                self.domain_strategy
            ));
        }
        if !(1..=1024).contains(&self.mux_concurrency) {
            return Err("Mux concurrency must be between 1 and 1024.".to_string());
        }
        if self.local_dns.chars().any(char::is_whitespace) {
            return Err("Local DNS must not contain spaces.".to_string());
        }
        if self.fake_dns_enabled {
            if ipv4_cidr(&self.fake_dns_ip_pool).is_none() {
                return Err(
                    "The FakeDNS pool must be an IPv4 CIDR such as 198.18.0.0/15.".to_string(),
                );
            }
            if self.fake_dns_pool_size == 0 {
                return Err("The FakeDNS pool size must be greater than zero.".to_string());
            }
        }
        if self.tun_enabled {
            if ipv4_cidr(&self.tun_gateway).is_none() {
                return Err("The TUN gateway must be an IPv4 CIDR such as 10.0.0.1/16.".to_string());
            }
            if !(576..=9000).contains(&self.tun_mtu) {
                return Err("The TUN MTU must be between 576 and 9000.".to_string());
            }
            if self.tun_name.chars().any(char::is_whitespace) {
                return Err("The TUN interface name must not contain spaces.".to_string());
            }
            if !TUN_STACKS.contains(&self.tun_stack.as_str()) {
                return Err(format!("Unknown TUN stack: {}", self.tun_stack));
            }
        }
        Ok(())
    }

    /// Persists every option. All keys are written on each change so the UI and
    /// the generated config never disagree about a partially saved state.
    pub fn save(&self, database: &Database) -> Result<(), String> {
        self.validate()?;

        let entries: [(&str, String); 19] = [
            (KEY_LOG_LEVEL, self.log_level.clone()),
            (KEY_DOMAIN_STRATEGY, self.domain_strategy.clone()),
            (KEY_BYPASS_CN, bool_value(self.bypass_cn)),
            (KEY_BYPASS_PRIVATE, bool_value(self.bypass_private)),
            (KEY_BLOCK_ADS, bool_value(self.block_ads)),
            (KEY_MUX_ENABLED, bool_value(self.mux_enabled)),
            (KEY_MUX_CONCURRENCY, self.mux_concurrency.to_string()),
            (KEY_IPV6_ENABLED, bool_value(self.ipv6_enabled)),
            (KEY_LOCAL_DNS, self.local_dns.clone()),
            (KEY_FAKE_DNS_ENABLED, bool_value(self.fake_dns_enabled)),
            (KEY_FAKE_DNS_POOL, self.fake_dns_ip_pool.clone()),
            (KEY_FAKE_DNS_POOL_SIZE, self.fake_dns_pool_size.to_string()),
            (KEY_TUN_ENABLED, bool_value(self.tun_enabled)),
            (KEY_TUN_NAME, self.tun_name.clone()),
            (KEY_TUN_MTU, self.tun_mtu.to_string()),
            (KEY_TUN_GATEWAY, self.tun_gateway.clone()),
            (KEY_TUN_AUTO_ROUTE, bool_value(self.tun_auto_route)),
            (KEY_TUN_STRICT_ROUTE, bool_value(self.tun_strict_route)),
            (KEY_TUN_STACK, self.tun_stack.clone()),
        ];

        for (key, value) in entries {
            database
                .set_setting(key, &value)
                .map_err(|error| format!("Could not save Xray settings: {error}"))?;
        }
        Ok(())
    }

    fn from_values(mut lookup: impl FnMut(&str) -> Option<String>) -> Self {
        let defaults = Self::default();

        let log_level = lookup(KEY_LOG_LEVEL)
            .filter(|value| is_known(value, LOG_LEVELS))
            .unwrap_or(defaults.log_level);
        let domain_strategy = lookup(KEY_DOMAIN_STRATEGY)
            .filter(|value| is_known(value, DOMAIN_STRATEGIES))
            .unwrap_or(defaults.domain_strategy);
        let bypass_cn = parse_bool(lookup(KEY_BYPASS_CN), defaults.bypass_cn);
        let bypass_private = parse_bool(lookup(KEY_BYPASS_PRIVATE), defaults.bypass_private);
        let block_ads = parse_bool(lookup(KEY_BLOCK_ADS), defaults.block_ads);
        let mux_enabled = parse_bool(lookup(KEY_MUX_ENABLED), defaults.mux_enabled);
        let mux_concurrency = lookup(KEY_MUX_CONCURRENCY)
            .and_then(|value| value.parse::<u16>().ok())
            .filter(|value| (1..=1024).contains(value))
            .unwrap_or(defaults.mux_concurrency);
        let ipv6_enabled = parse_bool(lookup(KEY_IPV6_ENABLED), defaults.ipv6_enabled);
        let local_dns = lookup(KEY_LOCAL_DNS)
            .map(|value| value.trim().to_string())
            .filter(|value| !value.chars().any(char::is_whitespace))
            .unwrap_or_default();
        let fake_dns_enabled = parse_bool(lookup(KEY_FAKE_DNS_ENABLED), defaults.fake_dns_enabled);
        let fake_dns_ip_pool = lookup(KEY_FAKE_DNS_POOL)
            .filter(|value| ipv4_cidr(value).is_some())
            .unwrap_or(defaults.fake_dns_ip_pool);
        let fake_dns_pool_size = lookup(KEY_FAKE_DNS_POOL_SIZE)
            .and_then(|value| value.parse::<u32>().ok())
            .filter(|value| (1..=1_000_000).contains(value))
            .unwrap_or(defaults.fake_dns_pool_size);
        let tun_enabled = parse_bool(lookup(KEY_TUN_ENABLED), defaults.tun_enabled);
        let tun_name = lookup(KEY_TUN_NAME)
            .map(|value| value.trim().to_string())
            .filter(|value| !value.chars().any(char::is_whitespace))
            .unwrap_or(defaults.tun_name);
        let tun_mtu = lookup(KEY_TUN_MTU)
            .and_then(|value| value.parse::<u32>().ok())
            .filter(|value| (576..=9000).contains(value))
            .unwrap_or(defaults.tun_mtu);
        let tun_gateway = lookup(KEY_TUN_GATEWAY)
            .filter(|value| ipv4_cidr(value).is_some())
            .unwrap_or(defaults.tun_gateway);
        let tun_auto_route = parse_bool(lookup(KEY_TUN_AUTO_ROUTE), defaults.tun_auto_route);
        let tun_strict_route = parse_bool(lookup(KEY_TUN_STRICT_ROUTE), defaults.tun_strict_route);
        let tun_stack = lookup(KEY_TUN_STACK)
            .filter(|value| is_known(value, TUN_STACKS))
            .unwrap_or(defaults.tun_stack);

        Self {
            log_level,
            domain_strategy,
            bypass_cn,
            bypass_private,
            block_ads,
            mux_enabled,
            mux_concurrency,
            ipv6_enabled,
            local_dns,
            fake_dns_enabled,
            fake_dns_ip_pool,
            fake_dns_pool_size,
            tun_enabled,
            tun_name,
            tun_mtu,
            tun_gateway,
            tun_auto_route,
            tun_strict_route,
            tun_stack,
        }
    }
}

fn is_known(value: &str, known: &[&str]) -> bool {
    known.contains(&value)
}

fn bool_value(value: bool) -> String {
    if value { "1" } else { "0" }.to_string()
}

fn parse_bool(value: Option<String>, default: bool) -> bool {
    match value.as_deref() {
        Some("1" | "true") => true,
        Some("0" | "false") => false,
        _ => default,
    }
}

/// Returns the prefix length when `value` is a valid IPv4 CIDR.
fn ipv4_cidr(value: &str) -> Option<u8> {
    let (address, prefix) = value.trim().split_once('/')?;
    address.parse::<std::net::Ipv4Addr>().ok()?;
    let prefix = prefix.parse::<u8>().ok()?;
    (prefix <= 32).then_some(prefix)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    fn load_from(values: &[(&str, &str)]) -> XraySettings {
        let values = values
            .iter()
            .map(|(key, value)| (key.to_string(), value.to_string()))
            .collect::<HashMap<_, _>>();
        XraySettings::from_values(|key| values.get(key).cloned())
    }

    #[test]
    fn defaults_are_used_when_nothing_is_stored() {
        let settings = load_from(&[]);
        assert_eq!(settings, XraySettings::default());
        assert_eq!(settings.log_level, "warning");
        assert_eq!(settings.domain_strategy, "IPIfNonMatch");
        assert!(settings.bypass_cn);
        assert!(settings.bypass_private);
        assert!(!settings.block_ads);
        assert!(!settings.mux_enabled);
        assert_eq!(settings.mux_concurrency, 8);
        assert!(settings.ipv6_enabled);
        assert!(settings.local_dns.is_empty());
        assert!(!settings.fake_dns_enabled);
        assert_eq!(settings.fake_dns_ip_pool, "198.18.0.0/15");
        assert_eq!(settings.fake_dns_pool_size, 65535);
        assert!(!settings.tun_enabled);
        assert_eq!(settings.tun_name, "cloak0");
        assert_eq!(settings.tun_mtu, 1500);
        assert_eq!(settings.tun_gateway, "10.0.0.1/16");
        assert!(settings.tun_auto_route);
        assert!(settings.tun_strict_route);
        assert_eq!(settings.tun_stack, "mixed");
    }

    #[test]
    fn stored_values_are_parsed() {
        let settings = load_from(&[
            (KEY_LOG_LEVEL, "debug"),
            (KEY_DOMAIN_STRATEGY, "AsIs"),
            (KEY_BYPASS_CN, "0"),
            (KEY_BYPASS_PRIVATE, "0"),
            (KEY_BLOCK_ADS, "1"),
            (KEY_MUX_ENABLED, "1"),
            (KEY_MUX_CONCURRENCY, "16"),
            (KEY_IPV6_ENABLED, "0"),
            (KEY_LOCAL_DNS, "223.5.5.5"),
            (KEY_FAKE_DNS_ENABLED, "1"),
            (KEY_FAKE_DNS_POOL, "198.18.0.0/16"),
            (KEY_FAKE_DNS_POOL_SIZE, "32768"),
            (KEY_TUN_ENABLED, "1"),
            (KEY_TUN_NAME, "cloak9"),
            (KEY_TUN_MTU, "1420"),
            (KEY_TUN_GATEWAY, "10.10.0.1/16"),
            (KEY_TUN_AUTO_ROUTE, "0"),
            (KEY_TUN_STRICT_ROUTE, "0"),
            (KEY_TUN_STACK, "gvisor"),
        ]);

        assert_eq!(settings.log_level, "debug");
        assert_eq!(settings.domain_strategy, "AsIs");
        assert!(!settings.bypass_cn);
        assert!(!settings.bypass_private);
        assert!(settings.block_ads);
        assert!(settings.mux_enabled);
        assert_eq!(settings.mux_concurrency, 16);
        assert!(!settings.ipv6_enabled);
        assert_eq!(settings.local_dns, "223.5.5.5");
        assert!(settings.fake_dns_enabled);
        assert_eq!(settings.fake_dns_ip_pool, "198.18.0.0/16");
        assert_eq!(settings.fake_dns_pool_size, 32768);
        assert!(settings.tun_enabled);
        assert_eq!(settings.tun_name, "cloak9");
        assert_eq!(settings.tun_mtu, 1420);
        assert_eq!(settings.tun_gateway, "10.10.0.1/16");
        assert!(!settings.tun_auto_route);
        assert!(!settings.tun_strict_route);
        assert_eq!(settings.tun_stack, "gvisor");
    }

    #[test]
    fn corrupt_values_fall_back_to_defaults() {
        let settings = load_from(&[
            (KEY_LOG_LEVEL, "verbose"),
            (KEY_DOMAIN_STRATEGY, "Always"),
            (KEY_BYPASS_CN, "maybe"),
            (KEY_MUX_CONCURRENCY, "0"),
            (KEY_FAKE_DNS_POOL, "not-a-cidr"),
            (KEY_FAKE_DNS_POOL_SIZE, "0"),
            (KEY_TUN_MTU, "10"),
            (KEY_TUN_GATEWAY, "10.0.0.1"),
            (KEY_TUN_STACK, "kernel"),
        ]);

        assert_eq!(settings, XraySettings::default());
    }

    #[test]
    fn validation_rejects_invalid_tun_and_fake_dns_values() {
        let mut settings = XraySettings::default();
        assert!(settings.validate().is_ok());

        settings.fake_dns_enabled = true;
        settings.fake_dns_ip_pool = "10.0.0.1".to_string();
        assert!(settings.validate().is_err());

        settings.fake_dns_ip_pool = "198.18.0.0/15".to_string();
        settings.tun_enabled = true;
        settings.tun_gateway = "fc00::1/64".to_string();
        assert!(settings.validate().is_err());

        settings.tun_gateway = "10.0.0.1/16".to_string();
        settings.tun_mtu = 100;
        assert!(settings.validate().is_err());

        settings.tun_mtu = 1500;
        settings.tun_stack = "kernel".to_string();
        assert!(settings.validate().is_err());

        settings.tun_stack = "system".to_string();
        assert!(settings.validate().is_ok());
    }

    #[test]
    fn empty_local_dns_is_valid() {
        let mut settings = XraySettings::default();
        settings.local_dns = String::new();
        assert!(settings.validate().is_ok());

        settings.local_dns = " 223.5.5.5 ".to_string();
        assert!(settings.validate().is_err());
    }
}
